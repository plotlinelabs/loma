  await page.unroute('**/work-api/knowledge');
  await library.getByRole('button',{name:'Save playbook',exact:true}).click();
  await library.getByRole('button',{name:/Invoice playbook QA/}).click();
  await page.screenshot({path:'/tmp/agents-knowledge-mobile.png'});
  assert(await library.evaluate(e => e.scrollWidth <= e.clientWidth + 1));
