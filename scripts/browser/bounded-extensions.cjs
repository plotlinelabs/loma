  await page.waitForTimeout(600);
  const bounds=await library.boundingBox(); assert(bounds.y >= 0 && bounds.width < 750, 'Desktop dialog placement');
  await page.screenshot({path:'/tmp/agents-knowledge-desktop.png'});
  await library.getByRole('button',{name:'Close',exact:true}).first().click();
  await page.getByRole('button',{name:'New work',exact:true}).click();
  const form=page.getByRole('dialog',{name:'Give an agent a job'});
  await form.locator('#agent').selectOption('bounded-qa');
  await form.locator('#job-title').fill('Playbook work QA');
  await form.locator('#instructions').fill('Summarize the attached source.');
  await form.locator('#success').fill('A sourced summary.');
  await form.getByRole('checkbox',{name:/Invoice playbook QA/}).check();
  const savedResponse=page.waitForResponse(r => r.url().endsWith('/work-api/work') && r.request().method()==='POST');
  await form.getByRole('button',{name:'Save paused work',exact:true}).click();
  const saved=await (await savedResponse).json(); assert.equal(saved.knowledge_ids.length,1);
  await form.waitFor({state:'hidden'});
  await page.goto(`${base}/tasks`);
  const board=page.getByRole('region',{name:'Agent work on your board',exact:true});
  await board.waitFor();
  await board.getByText(/Show agent work cards/).click();
  await board.getByRole('link',{name:/Playbook work QA/}).waitFor();
  assert.equal(await board.getByRole('button',{name:/Approve/}).count(),0);
  await page.screenshot({path:'/tmp/agents-board-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await board.scrollIntoViewIfNeeded();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({path:'/tmp/agents-board-mobile.png'});
  await board.getByRole('link',{name:/Playbook work QA/}).click();
  await page.waitForURL(/agents\/work.*#work-/);
  await page.getByRole('region',{name:'Playbook work QA',exact:true}).waitFor();
  await page.getByRole('button',{name:'Playbook library',exact:true}).click();
  await library.getByRole('button',{name:/Invoice playbook QA/}).click();
  await library.getByRole('button',{name:'Delete playbook',exact:true}).click();
  await library.getByRole('button',{name:'Keep playbook',exact:true}).click();
  await library.getByRole('button',{name:'Delete playbook',exact:true}).click();
  await library.getByRole('button',{name:'Confirm delete',exact:true}).click();
  await library.getByRole('status').filter({hasText:'Playbook deleted'}).waitFor();
  await library.getByRole('button',{name:'Close',exact:true}).first().click();
  execFileSync(path.join(root,'.venv/bin/python'), [path.join(root,'tests/e2e/bounded_fixture.py'),'slack-proposal'], {cwd:root});
  await page.goto(`${base}/agents/work?tab=needs`);
  await page.getByRole('button',{name:'Review exact action',exact:true}).click();
  const approval=page.getByRole('dialog',{name:'Review before authorizing',exact:true});
  assert.match(await approval.innerText(),/Slack channel ID/);
  await approval.getByRole('button',{name:'Approve & send',exact:true}).click();
  await approval.waitFor({state:'hidden'});
  execFileSync(path.join(root,'.venv/bin/python'), [path.join(root,'tests/e2e/bounded_fixture.py'),'slack-timeout'], {cwd:root});
  await page.reload();
  await page.getByRole('button',{name:'Investigate delivery',exact:true}).click();
  const slack=page.getByRole('dialog',{name:'Investigate Slack delivery',exact:true});
